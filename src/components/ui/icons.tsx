import type { SVGProps } from "react";

/**
 * Inline icon set.
 *
 * These replaced single Unicode characters (pencil, envelope, shield, star) that read fine in
 * a design tool and rendered as empty boxes whenever the active font lacked the glyph. A
 * missing glyph is worse than no icon: the control looks broken rather than plain.
 *
 * Rules this file keeps:
 *   - every icon is `aria-hidden`, because the label next to it carries the meaning. An icon
 *     that is announced twice ("pencil, Add News") is noise in a screen reader.
 *   - stroke icons use `currentColor` so they inherit the button's text colour, including
 *     its dark/light state, instead of hard-coding a palette that can drift.
 *   - no icon is the only signal for anything. Colour, glyph and text never disagree.
 */

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ children, ...props }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.7}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

